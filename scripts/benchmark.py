"""Headless synthetic-frame performance benchmark."""

from __future__ import annotations

import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np
import trimesh

from src.rendering.projection_3d import project_points, rotation_matrix
from src.rendering.wireframe_renderer import WireframeRenderer
from src.vision.hand_tracker import HandTracker

WIDTH, HEIGHT = 640, 480
WARMUP_FRAMES = 30
MEASURED_FRAMES = 300
RUNTIME_CAP_SECONDS = 600
EMA_ALPHA = 0.05


def _check_runtime(start: float) -> None:
    if time.perf_counter() - start > RUNTIME_CAP_SECONDS:
        raise TimeoutError("Benchmark exceeded ten-minute runtime cap")


def _models():
    cube = trimesh.creation.box(extents=(150, 150, 150))
    return {
        "cube": cube,
        "icosphere-3": trimesh.creation.icosphere(subdivisions=3, radius=75),
        "icosphere-5": trimesh.creation.icosphere(subdivisions=5, radius=75),
    }


def _render_once(renderer, vertices, edges, frame, force_lod):
    rot = rotation_matrix(0.17, 0.31, 0.0)
    points = project_points(vertices, rot, 1.0, (0, 0), frame.shape)
    depths = (vertices @ rot.T)[:, 2] + 1500.0
    return renderer.draw(frame, points, edges, depth=depths, force_lod=force_lod)


def run_benchmark(output_path: str | Path = "docs/BENCHMARK.md") -> str:
    measured = int(os.environ.get("HOLOFORGE_BENCH_FRAMES", MEASURED_FRAMES))
    if measured < 1:
        raise ValueError("HOLOFORGE_BENCH_FRAMES must be positive")
    start = time.perf_counter()
    frame = np.zeros((HEIGHT, WIDTH, 3), dtype=np.uint8)
    inference_ema = None
    tracker = None
    model_path = Path("models/hand_landmarker.task")
    if model_path.is_file():
        try:
            tracker = HandTracker(str(model_path))
            for index in range(WARMUP_FRAMES):
                tracker.detect(frame, index + 1)
                _check_runtime(start)
            inference_ema = 0.0
            for index in range(measured):
                tick = time.perf_counter()
                tracker.detect(frame, WARMUP_FRAMES + index + 1)
                elapsed = (time.perf_counter() - tick) * 1000
                inference_ema = (1 - EMA_ALPHA) * inference_ema + EMA_ALPHA * elapsed
                _check_runtime(start)
        finally:
            if tracker is not None:
                tracker.close()

    rows = []
    models = _models()
    _check_runtime(start)
    for name, mesh in models.items():
        vertices = np.asarray(mesh.vertices, dtype=np.float64)
        edges = np.asarray(mesh.edges_unique, dtype=np.intp)
        for target in (5000, 1200):
            renderer = WireframeRenderer(holographic=True)
            renderer.prepare_lod(edges)
            for _ in range(WARMUP_FRAMES):
                _render_once(renderer, vertices, edges, frame, target)
                _check_runtime(start)
            render_ema = 0.0
            for _ in range(measured):
                tick = time.perf_counter()
                _render_once(renderer, vertices, edges, frame, target)
                elapsed = (time.perf_counter() - tick) * 1000
                render_ema = (1 - EMA_ALPHA) * render_ema + EMA_ALPHA * elapsed
                _check_runtime(start)
            rows.append((name, target, renderer.active_edge_count, render_ema))

    inference_text = "unavailable (model bundle missing)" if inference_ema is None else f"{inference_ema:.2f} ms"
    lines = [
        "# HoloForge Synthetic Render Benchmark",
        "",
        f"Synthetic frame: {WIDTH}x{HEIGHT}; warmup: {WARMUP_FRAMES}; measured: {measured}.",
        f"Inference EMA on synthetic frames: {inference_text}.",
        "Render times are EMA in milliseconds and exclude warmup frames.",
        "",
        "| Model | Forced LOD | Edges drawn | Render EMA (ms) |",
        "|---|---:|---:|---:|",
    ]
    lines.extend(f"| {name} | {target} | {count} | {elapsed:.3f} |"
                 for name, target, count, elapsed in rows)
    lines.extend(("", "Generated by `scripts/benchmark.py`; timings are machine-dependent.", ""))
    report = "\n".join(lines)
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report, encoding="utf-8")
    return report


if __name__ == "__main__":
    print(run_benchmark())
